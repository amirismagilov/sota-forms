#!/usr/bin/env bash
# Выкат на прод-хост одной командой.
#
#     ./scripts/deploy.sh              # с git pull
#     ./scripts/deploy.sh --skip-pull  # код уже обновлён (так зовёт CI)
#
# Зачем отдельный скрипт, а не три команды руками: фронт на этом хосте
# обновляется НЕ так, как остальное, и об этом легко забыть — что и случилось
# 2026-08-14, когда выкатился новый бэкенд со старым интерфейсом.
#
# frontend/Dockerfile запекает исходники внутрь образа (COPY . .), бинд-маунта
# кода нет, а сам сервис сидит в profiles: ["build"] — поэтому обычный
# `docker compose up --build` его образ НЕ трогает, а сборка бандла честно
# отрабатывает на устаревшем коде. Отсюда обязательный явный шаг пересборки
# образа перед сборкой бандла.
#
# Скрипт ничего не предполагает молча: если хост не в режиме «nginx отдаёт
# статику», он скажет об этом, а не сделает вид, что фронт обновлён.
set -euo pipefail
cd "$(dirname "$0")/.."

SKIP_PULL=""
[ "${1:-}" = "--skip-pull" ] && SKIP_PULL=1

if [ -z "$SKIP_PULL" ]; then
  echo "==> обновляем код"
  git pull origin main
fi

echo "==> пересобираем бэкенд и воркер"
# Без `down`: статику отдаёт nginx и от контейнеров она не зависит, поэтому API
# простаивает только на время пересоздания контейнера, а не всю сборку.
docker compose up -d --build

if [ -x ./rebuild-frontend.sh ]; then
  echo "==> пересобираем образ фронта из свежего кода"
  docker compose --profile build build frontend

  echo "==> собираем бандл и подменяем его под nginx"
  ./rebuild-frontend.sh

  # Бандл собрался — но из свежего ли кода? По хэшу файла этого не понять: он
  # меняется и при пересборке старого исходника. Сверяем время сборки бандла с
  # временем выкатываемого коммита — бандл обязан быть новее.
  #
  # Раньше здесь сверялось время ОБРАЗА через `docker compose images -q frontend`,
  # и это было неверно: compose перечисляет образы созданных контейнеров, а фронт
  # тут — разовый `run --rm`, контейнера у него нет. Команда возвращала пустоту,
  # `docker image inspect ""` падал, дата вырождалась в полночь — и успешный
  # выкат объявлялся неуспешным (2026-08-14). Проверка не должна зависеть от того,
  # как compose называет образы.
  echo "==> проверяем, что бандл собран из выкаченного кода"
  if [ ! -s frontend/dist/index.html ]; then
    echo "!! frontend/dist/index.html пуст или отсутствует — бандл не подменился" >&2
    exit 1
  fi
  dist_ts=$(stat -c %Y frontend/dist/index.html)
  commit_ts=$(git log -1 --format=%ct)
  if [ "$dist_ts" -lt "$commit_ts" ]; then
    echo "!! бандл старше выкаченного коммита ($(date -d @"$dist_ts" +'%F %T') < $(date -d @"$commit_ts" +'%F %T'))" >&2
    echo "!! сборка фронта не отработала — интерфейс остался бы прежним" >&2
    exit 1
  fi

else
  # Молчать здесь нельзя: человек уйдёт в уверенности, что фронт обновлён.
  echo "!! rebuild-frontend.sh не найден — фронт НЕ обновлён." >&2
  echo "!! Этот скрипт рассчитан на хост, где nginx отдаёт статику из frontend/dist" >&2
  echo "!! (см. docker-compose.override.yml). Если фронт у вас крутится сервисом," >&2
  echo "!! он обновился вместе с остальными на шаге выше." >&2
fi

echo "==> ждём здоровья бэкенда"
ok=""
for _ in $(seq 1 30); do
  if curl -sf localhost:8000/api/health >/dev/null; then ok=1; break; fi
  sleep 2
done
if [ -z "$ok" ]; then
  echo "!! бэкенд не отвечает на /api/health — выкат неуспешен" >&2
  docker compose logs --tail=80 backend
  exit 1
fi

docker compose ps
echo "==> готово @ $(date +'%F %T')"
